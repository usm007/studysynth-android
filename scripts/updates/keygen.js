#!/usr/bin/env node
/**
 * Creates the StudySynth update signing key pair.
 *
 *   node scripts/updates/keygen.js [--write-app-key] [--force]
 *
 * Algorithm: RSA-3072 with SHA-256 (PKCS#1 v1.5). This is not an arbitrary
 * choice: @capawesome/capacitor-live-update verifies bundle signatures
 * natively with `Signature.getInstance("SHA256withRSA")` and an RSA
 * SubjectPublicKeyInfo key, so the OTA channel must use RSA. The same key
 * signs the manifest and content packages, and WebCrypto supports
 * RSASSA-PKCS1-v1_5/SHA-256 in every Android WebView that has crypto.subtle.
 *
 * The private key is written OUTSIDE the repository. Never commit it.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');

const args = process.argv.slice(2);
const force = args.includes('--force');
const writeAppKey = args.includes('--write-app-key');

const dir = path.join(os.homedir(), '.studysynth');
const keyFile = path.join(dir, 'update-signing-key.pem');
const pubFile = path.join(dir, 'update-public-key.pem');
const appKeyFile = path.resolve(__dirname, '..', '..', 'pwa', 'updates', 'keys.js');

if (fs.existsSync(keyFile) && !force) {
  console.error(`A signing key already exists at ${keyFile}. Re-run with --force to replace it.`);
  console.error('Replacing it invalidates every previously published signature and requires a new APK.');
  process.exit(1);
}

fs.mkdirSync(dir, { recursive: true });

const { privateKey, publicKey } = crypto.generateKeyPairSync('rsa', { modulusLength: 3072 });
fs.writeFileSync(keyFile, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
fs.writeFileSync(pubFile, publicKey.export({ type: 'spki', format: 'pem' }));

const spkiB64 = publicKey.export({ type: 'spki', format: 'der' }).toString('base64');

if (writeAppKey) {
  const contents = `/**
 * StudySynth update verification key.
 *
 * Generated by scripts/updates/keygen.js. This is a PUBLIC key: it can only
 * verify signatures, never create them. Rotating it requires a new APK.
 */
(function (global) {
  'use strict';
  global.STUDYSYNTH_UPDATE_PUBLIC_KEY = '${spkiB64}';
  global.STUDYSYNTH_UPDATE_KEY_ID = 'rsa3072-${spkiB64.slice(-12)}';
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.writeFileSync(appKeyFile, contents);
  console.log(`Public key embedded in ${path.relative(process.cwd(), appKeyFile)}`);
}

console.log(`Private key: ${keyFile}`);
console.log(`Public key : ${pubFile}`);
console.log('');
console.log('Add the private key to GitHub as the OTA_SIGNING_KEY secret:');
console.log(`  gh secret set OTA_SIGNING_KEY --body "$(base64 -w0 ~/.studysynth/update-signing-key.pem)"`);
