/**
 * Builds the Capacitor web payload from the PWA sources.
 *
 * Only runtime files are copied, so development dependencies, tests and
 * fixtures never end up inside the APK or the OTA bundle. The version stamp
 * is generated here so the web app always knows what it is running.
 */
const fs = require('fs');
const path = require('path');
const { readVersion } = require('./version');

const root = path.resolve(__dirname, '..');
const src = path.join(root, 'pwa');
const out = path.join(root, 'www');
const version = readVersion();

const files = [
  'index.html',
  'styles.css',
  'app.css',
  'app.js',
  'sample_data.js',
  'ctet_index.js',
  'ctet_manifest.js',
  'manifest.webmanifest',
  'sw.js'
];
const dirs = ['assets', 'engine', 'vendor', 'ctet', 'updates'];

if (!fs.existsSync(out)) {
  fs.mkdirSync(out, { recursive: true });
} else {
  for (const entry of fs.readdirSync(out)) {
    try {
      fs.rmSync(path.join(out, entry), { recursive: true, force: true });
    } catch (e) {
      // ignore transient locks
    }
  }
}

for (const file of files) {
  const from = path.join(src, file);
  if (!fs.existsSync(from)) throw new Error(`Missing PWA runtime file: ${file}`);
  fs.copyFileSync(from, path.join(out, file));
}

for (const dir of dirs) {
  const from = path.join(src, dir);
  if (!fs.existsSync(from)) throw new Error(`Missing PWA runtime directory: ${dir}`);
  fs.cpSync(from, path.join(out, dir), { recursive: true });
}

const stamp = `/* Generated by scripts/build-web.js - do not edit. */\n` +
  `(function (global) {\n` +
  `  'use strict';\n` +
  `  global.STUDYSYNTH_VERSION = ${JSON.stringify({
    versionName: version.versionName,
    versionCode: version.versionCode,
    minSupportedVersionCode: version.minSupportedVersionCode,
    runtimeVersion: version.runtimeVersion,
    contentVersion: version.contentVersion,
    packageId: version.packageId,
    channel: version.channel,
    builtAt: new Date().toISOString()
  }, null, 2)};\n` +
  `})(typeof window !== 'undefined' ? window : globalThis);\n`;
fs.writeFileSync(path.join(out, 'version.js'), stamp);

// The committed development stamp must describe the same version, otherwise a
// developer testing pwa/ locally would exercise the wrong update paths.
const devStamp = fs.readFileSync(path.join(src, 'version.js'), 'utf8');
for (const key of ['versionName', 'versionCode', 'runtimeVersion', 'contentVersion', 'packageId', 'channel']) {
  const expected = String(version[key]);
  const pattern = new RegExp(`${key}:\\s*['"]?${expected.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"]?`);
  if (!pattern.test(devStamp)) {
    throw new Error(`pwa/version.js is out of date for "${key}" (expected ${expected}). Update it to match version.json.`);
  }
}

const total = (function walk(p) {
  let bytes = 0;
  for (const entry of fs.readdirSync(p, { withFileTypes: true })) {
    const child = path.join(p, entry.name);
    bytes += entry.isDirectory() ? walk(child) : fs.statSync(child).size;
  }
  return bytes;
})(out);

console.log(`PWA web payload ready: ${path.relative(root, out)} (${(total / 1024 / 1024).toFixed(1)} MB) v${version.versionName} (${version.versionCode})`);
