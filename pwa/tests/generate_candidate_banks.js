const DEFAULT_PDF_DIR = process.env.NCERT_PDF_DIR || '/home/hatch/workspace/ncert_pdfs';
const DEFAULT_OUT_DIR = path.resolve(__dirname, '../data/ncert_8_2_candidates');

function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

function parseArgs(argv) {
  const out = { pdfDir: DEFAULT_PDF_DIR, outDir: DEFAULT_OUT_DIR };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--pdf-dir' && argv[i + 1]) out.pdfDir = argv[++i];
    else if (argv[i] === '--out-dir' && argv[i + 1]) out.outDir = argv[++i];
  }
  return out;
}

function loadJson(file) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (Array.isArray(data)) return data;
  if (Array.isArray(data.entries)) return data.entries;
  if (Array.isArray(data.rows)) return data.rows;
  return data;
}

function renderBank(bank) {
  const lines = [];
  lines.push('# NCERT Class 8 Social Science — Candidate Question Bank (Coverage Engine)');
  lines.push('## Chapter ' + bank.chapter_num + ': ' + bank.title);
  lines.push('');
  lines.push('- **Source Document:** `' + bank.pdf + '`');
  lines.push('- **Status:** CANDIDATE — generated by the coverage engine for review. NOT a production bank.');
  lines.push('- **Candidate Engine Version:** ' + bank.version + ' (baseline ' + BASELINE_COMMIT + ')');
  lines.push('- **Pages Processed:** ' + bank.pages_processed);
  lines.push('- **Total Candidate Questions:** ' + bank.questions.length + ' items');
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Part I: Candidate Questions');
  lines.push('');
  bank.questions.forEach((q, idx) => {
    const t = q.traceability || {};
    lines.push('### Question ' + (idx + 1) + ' [' + q.id + ']');
    lines.push('- **Subtype:** `' + q.question_subtype + '`');
    lines.push('- **Difficulty:** `' + (q.difficulty || 'medium') + '`');
    lines.push('- **Cognitive Category:** `' + (q.cognitive_level || 'recall') + '`');
    lines.push('- **Answer Key:** **' + q.answer_key + '**');
    lines.push('- **Fact:** `' + (t.fact_id || '') + '`');
    lines.push('- **Source:** page ' + ((t.page_range || []).join(', ') || '') +
      ', unit `' + (t.unit_id || '') + '`' +
      ((t.block_ids || []).length ? ', blocks `' + t.block_ids.join(', ') + '`' : '') +
      (t.evidence_source ? ', evidence `' + t.evidence_source + '`' : '') +
      (t.figure_ref ? ', figure `' + t.figure_ref + '`' : ''));
    lines.push('- **Generation Rule:** `' + (t.rule || '') + '`');
    lines.push('');
    lines.push('**Stem:**');
    lines.push('> ' + q.stem);
    lines.push('');
    lines.push('**Options:**');
    for (const opt of q.options) {
      let line = '- **' + opt.key + ')** ' + opt.text;
      if (opt.is_correct) line += ' **(CORRECT ANSWER)**';
      else if (opt.distractor_origin) line += ' *(Distractor Origin: `' + opt.distractor_origin + '`)*';
      lines.push(line);
    }
    lines.push('');
    lines.push('**Supporting Textbook Excerpt:**');
    lines.push('> "' + (q.supporting_excerpt || '') + '"');
    lines.push('');
    lines.push('**Explanation:**');
    lines.push(q.explanation || '');
    lines.push('');
    lines.push('---');
    lines.push('');
  });
  return lines.join('\n');
}

async function runGeneration(pdfDir, outDir) {
  // Node polyfills required by the vendored pdf.js build (same as Phase 2E).
  if (!Uint8Array.prototype.toHex) {
    Uint8Array.prototype.toHex = function () { return Buffer.from(this).toString('hex'); };
  }
  if (!Math.sumPrecise) {
    Math.sumPrecise = function (arr) {
      let sum = 0;
      for (const n of arr) sum += Number(n) || 0;
      return sum;
    };
  }
  const Parser = require('../engine/pdfParser.js');
  const DocumentModel = require('../engine/documentModel.js');
  const SourceReconstruction = require('../engine/sourceReconstruction.js');
  const Engine = require('../engine/generator.js');
  const Builder = require('../engine/coverageBuilder.js');
  const pdfjs = await import(pathToFileURL(path.resolve(__dirname, '../vendor/pdfjs/pdf.mjs')).href);

  // 1. Verify ALL inputs before processing anything.
  const buffers = new Map();
  for (const ch of CHAPTERS) {
    const pdfPath = path.join(pdfDir, ch.file);
    if (!fs.existsSync(pdfPath)) {
      throw new Error('MISSING PDF: ' + ch.file + ' not found in ' + pdfDir + ' — aborting, nothing written.');
    }
    const buf = fs.readFileSync(pdfPath);
    const hash = sha256(buf);
    if (hash !== ch.sha256) {
      throw new Error('HASH MISMATCH: ' + ch.file + ' sha256 ' + hash + ' != expected ' + ch.sha256 + ' — aborting, nothing written.');
    }
    buffers.set(ch.code, buf);
  }

  // Chapter 3 inventory + Phase 2A matrix (read-only; never modified).
  const diagDir = path.resolve(__dirname, '../../diagnostics');
  const inventory = loadJson(path.join(diagDir, 'chapter_3_knowledge_inventory.json'));
  const phase2aMatrix = loadJson(path.join(diagDir, 'chapter_3_phase2a_coverage_matrix.json'));

  const banks = [];
  const traceability = { version: Builder.COVERAGE_ENGINE_VERSION, baseline_commit: BASELINE_COMMIT, chapters: [] };
  const validationSummary = { version: Builder.COVERAGE_ENGINE_VERSION, baseline_commit: BASELINE_COMMIT, chapters: [], totals: null };
  let totalAccepted = 0;
  let totalFacts = 0;

  for (const ch of CHAPTERS) {
    const buf = buffers.get(ch.code);
    const doc = await pdfjs.getDocument({
      data: new Uint8Array(buf), isEvalSupported: false, useSystemFonts: true, disableFontFace: true,
    }).promise;
    const layouts = [];
    for (let pageNum = 1; pageNum <= doc.numPages; pageNum++) {
      const page = await doc.getPage(pageNum);
      const layout = await Parser.extractPageLayout(page, pageNum);
      layouts.push({
        pageNumber: layout.pageNumber, blocks: layout.blocks, stats: layout.stats,
        bodyText: layout.bodyText, bodyOnlyText: layout.bodyOnlyText,
      });
      page.cleanup();
    }
    const docModel = DocumentModel.buildStructuredDocument(layouts, { documentId: ch.code, sourceTitle: ch.title });
    const recon = SourceReconstruction.reconstructDocument(docModel, { documentId: ch.code });
    const typed = Engine.buildTypedKnowledgeFromReconstructedUnits(recon.units,
      { sourceMeta: { type: 'textbook', grade: 8, subject: 'social science' }, documentId: ch.code });
    const isCh3 = ch.code === 'hees203';
    const bank = Builder.buildCandidateBank({
      chapterCode: ch.code,
      chapterNum: ch.num,
      title: ch.title,
      pdfFile: ch.file,
      pagesProcessed: layouts.length + '/' + doc.numPages,
      typedFacts: typed.typed_facts,
      inventoryEntries: isCh3 ? inventory : null,
      phase2aRows: isCh3 ? phase2aMatrix : null,
    });
    banks.push(bank);
    traceability.chapters.push({
      chapter: ch.code, chapter_num: ch.num, pdf: ch.file, sha256: ch.sha256,
      pages: doc.numPages, units: recon.units.length,
      questions: bank.traceability.questions,
      fact_dispositions: bank.traceability.fact_dispositions,
    });
    validationSummary.chapters.push({
      chapter: ch.code, chapter_num: ch.num, pdf: ch.file,
      validation: bank.validation,
    });
    totalAccepted += bank.questions.length;
    totalFacts += bank.validation.facts_in;
    console.log(ch.code + ': ' + bank.questions.length + ' candidate questions from ' +
      bank.validation.facts_in + ' typed facts (rejected ' + bank.validation.rejected_candidates +
      ', stem collisions ' + bank.validation.stem_collisions_rejected + ')');
  }

  validationSummary.totals = { chapters: banks.length, typed_facts: totalFacts, accepted_questions: totalAccepted };

  // 2. Write ONLY the candidate output directory.
  fs.mkdirSync(outDir, { recursive: true });
  const manifestChapters = [];
  for (const bank of banks) {
    const fileName = bank.chapter + '_candidate_bank.md';
    fs.writeFileSync(path.join(outDir, fileName), renderBank(bank), 'utf8');
    manifestChapters.push({
      chapter: bank.chapter_num, chapter_code: bank.chapter, title: bank.title,
      file: bank.pdf, pages_processed: bank.pages_processed,
      candidate_count: bank.questions.length, bank_file: fileName,
    });
  }
  fs.writeFileSync(path.join(outDir, 'candidate_manifest.json'),
    JSON.stringify({ version: Builder.COVERAGE_ENGINE_VERSION, baseline_commit: BASELINE_COMMIT,
      chapters: manifestChapters }, null, 2) + '\n', 'utf8');
  const ch3 = banks.find((b) => b.chapter === 'hees203');
  if (ch3 && ch3.coverage) {
    fs.writeFileSync(path.join(outDir, 'chapter_3_coverage_matrix.json'),
      JSON.stringify({ version: Builder.COVERAGE_ENGINE_VERSION, baseline_commit: BASELINE_COMMIT,
        chapter: 'hees203', inventory_file: 'diagnostics/chapter_3_knowledge_inventory.json (unchanged)',
        denominator_note: 'Question-worthy entries only: question_suitable == yes (143). Excluded: 17.',
        summary: ch3.coverage.summary, rows: ch3.coverage.rows }, null, 2) + '\n', 'utf8');
  }
  fs.writeFileSync(path.join(outDir, 'traceability.json'),
    JSON.stringify(traceability, null, 2) + '\n', 'utf8');
  fs.writeFileSync(path.join(outDir, 'validation_summary.json'),
    JSON.stringify(validationSummary, null, 2) + '\n', 'utf8');

  return { banks: banks, outDir: outDir, totals: validationSummary.totals };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const result = await runGeneration(args.pdfDir, args.outDir);
  console.log('Wrote ' + result.banks.length + ' candidate banks to ' + result.outDir +
    ' (' + result.totals.accepted_questions + ' questions from ' + result.totals.typed_facts + ' typed facts).');
  return result;
}

if (require.main === module) {
  main().catch((err) => { console.error('GENERATION FAILED: ' + (err && err.message ? err.message : err)); process.exit(1); });
}

