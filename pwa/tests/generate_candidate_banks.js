/**
 * StudySynth — Coverage-Driven Candidate Bank Generation (Delivery Pivot).
 *
 * Reproducible command (run from pwa/):
 *   NCERT_PDF_DIR=/path/to/pdfs node tests/generate_candidate_banks.js
 *   node tests/generate_candidate_banks.js --pdf-dir /path/to/pdfs [--out-dir <dir>]
 *
 * For every configured NCERT Class 8 PDF it runs the shadow pipeline
 * (page layouts -> structured document model -> source reconstruction ->
 * typed-knowledge adapter) and the coverage-driven question builder, and
 * writes candidate banks to a SEPARATE output directory. It never writes to
 * pwa/data/ncert_8_2_staged/, never touches the consolidated file or the
 * production manifest, and never modifies a production bank.
 *
 * Safety:
 * - Every PDF SHA-256 is verified against CHAPTERS before any chapter is
 *   processed. A missing file or a hash mismatch aborts the whole run with
 *   a clear error and writes nothing.
 * - Outputs contain no timestamps and no absolute paths, so repeated runs
 *   are byte-identical (verified by the delivery report).
 * - Default PDF dir follows the Phase 2E harness convention
 *   (NCERT_PDF_DIR env, else /home/hatch/workspace/ncert_pdfs); pass
 *   --pdf-dir to override. Default output dir is
 *   pwa/data/ncert_8_2_candidates/.
 */
